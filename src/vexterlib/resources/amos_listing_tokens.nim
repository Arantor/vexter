proc amosExtensionToken*(extension, token: int): string =
  case extension
  of 1:
    case token
    of 0x002c: "Music Off "
    of 0x004c: "Tempo "
    of 0x0058: "Music "
    of 0x00f8: "Sam Play "
    of 0x0104: "Sam Raw "
    of 0x0118: "Bell "
    of 0x01a4, 0x01b2: "Volume "
    of 0x01d6: "Led Off "
    of 0x01e4: "Say "
    of 0x01fa: "Set Talk "
    else: ""
  of 2:
    if token == 0x0056: "Unpack " else: ""
  of 4:
    case token
    of 0x0006: "Td Debug "
    of 0x0016: "Td Load "
    of 0x0024: "Td Clear All"
    of 0x0036: "Td Object "
    of 0x0090: "Td Kill "
    of 0x00d4: "Td Move Rel "
    of 0x00ec: "Td Move "
    of 0x0100: "Td Forward "
    of 0x0114: "Td Position X"
    of 0x0128: "Td Position Y"
    of 0x013c: "Td Position Z"
    of 0x01d0: "Td Attitude B"
    of 0x0328: "Td Set Zone "
